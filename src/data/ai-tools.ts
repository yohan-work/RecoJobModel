// 헬퍼 함수들
export function getToolById(id: string): AITool | undefined {
  return aiTools.find((tool) => tool.id === id);
}

export function getToolsByRole(role: string): AITool[] {
  return aiTools.filter((tool) => tool.roles.includes(role as any));
}

export function getToolsByCategory(category: string): AITool[] {
  return aiTools.filter((tool) => tool.category.includes(category as any));
}

export function getTrendingTools(): AITool[] {
  return aiTools.filter((tool) => tool.trending);
}

export function getNewTools(): AITool[] {
  return aiTools.filter((tool) => tool.new);
}

export function getPopularTools(limit: number = 10): AITool[] {
  return [...aiTools].sort((a, b) => b.popularity - a.popularity).slice(0, limit);
}

export function getFreeTools(): AITool[] {
  return aiTools.filter(
    (tool) => tool.pricing.tier === "free" || tool.pricing.tier === "freemium"
  );
}

export function searchTools(query: string): AITool[] {
  const lowerQuery = query.toLowerCase();
  return aiTools.filter(
    (tool) =>
      tool.name.toLowerCase().includes(lowerQuery) ||
      tool.description.toLowerCase().includes(lowerQuery) ||
      tool.tagline.toLowerCase().includes(lowerQuery) ||
      tool.features.some((f) => f.toLowerCase().includes(lowerQuery))
  );
}

